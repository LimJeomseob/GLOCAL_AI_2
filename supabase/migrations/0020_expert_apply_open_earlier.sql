-- 교내 AI활용 전문가 신청 시작일 앞당김 — 9. 9.(수) → 9. 7.(월)
--
-- 공문의 신청기간은 ´26. 9. 9.(수) ~ 9. 18.(금)이나, 신청 시스템이 먼저 준비되어
-- AI융합원이 접수를 이틀 앞당기기로 했다(2026. 9. 7. 결정). 마감은 공문과 같다.
--
-- 0019의 update문은 `expert_apply_open_at is null` 조건이 붙어 있어 이미 값이 들어간
-- 행을 덮지 않는다. 그래서 여기서 다시 지정한다. 화면의 「신청기간」 표기는
-- studyGroupConstants.ts의 STUDY_EXPERT_OVERVIEW에 있으며 같은 커밋에서 함께 바꿨다 —
-- 접수 허용 구간의 정본은 이 컬럼이고 상수는 안내 문구일 뿐이므로 둘이 어긋나면
-- 신청자가 "기간인데 왜 막히는가"로 문의하게 된다.
-- ============================================================================

update public.study_rounds
set expert_apply_open_at = '2026-09-07T00:00:00+09:00'
where year = 2026 and semester = '2학기';
